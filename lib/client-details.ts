export type PriceLineView = {
  /** 기준 — 월 · 건당 · 첫 제작 · 월 유지보수 */
  basis: string;
  /** "200,000" — 금액 미정이면 null */
  amount: string | null;
  from: boolean;
  /** "월 200,000원" */
  text: string;
};

/** 비용 표기 — 줄마다 기준 · 금액, text 는 한 줄로 이은 것 */
export function priceOf(service: Service): { lines: PriceLineView[]; text: string; note?: string; notice?: string } {
  const price = CLIENT_PRICES[service.id];
  const lines = (price?.lines ?? [{ cycle: "건", amount: null }]).map((line) => {
    const basis = line.label ?? (line.cycle === "월" ? "월" : "건당");
    const amount = line.amount === null ? null : line.amount.toLocaleString("ko-KR");
    const from = Boolean(line.from);
    const value = amount === null ? "견적 협의" : `${amount}원${from ? "~" : ""}`;
    return { basis, amount, from, text: `${basis} ${value}` };
  });
  return { lines, text: lines.map((line) => line.text).join("·"), note: price?.note, notice: price?.notice };
}

/** 한 줄 비용 — "월 200,000원" · "첫 제작 2,000,000원·월 유지보수 100,000원" */
export const priceText = (service: Service) => priceOf(service).text;

/** 진행 기준 칩 — "월 단위" · "건당" · "첫 제작 + 월 유지보수" */
export const billingBasis = (service: Service) =>
  priceOf(service)
    .lines.map((line) => (line.basis === "월" ? "월 단위" : line.basis))
    .join(" + ");
